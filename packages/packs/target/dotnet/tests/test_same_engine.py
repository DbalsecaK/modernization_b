"""`same_database` in the .NET pack (ADR-0055, ADR-0056 phase H): the project talks to the legacy's Sybase ASE through
AdoNetCore.AseClient, the unit of work is the legacy's own T-SQL on the request's connection, and the port that replaces
sp_debito gets an adapter the platform writes. The live test runs the reference service against the platform's Sybase
on a private network (opt-in: NEXTI_LIVE_ASE=1; needs datagrip/sybase:16.0 and the .NET sandbox image)."""

