"""The target against the legacy's own engine (ADR-0055, point 10): with `same_database` the reference service, its
hand-written T-SQL adapters and the generated adapter of sp_debito run their golden master against the platform's
Sybase ASE on a private network (the suite's tables, the transactional substitutes, the call log), through jTDS from
the Java sandbox. Needs Docker, the image datagrip/sybase:16.0 (9 GB) and the Java sandbox image with jTDS; opt-in:
NEXTI_LIVE_ASE=1."""

import asyncio
import os
import subprocess
from pathlib import Path

import pytest

from nexti_adapter_sybase.ase import RecordedRunner, SameEngine
from nexti_core.adapters import SourceFile
from nexti_core.spec.characterization import GoldenMaster, Suite
from nexti_orchestration.generation import wiring
from nexti_pack_spring_boot import IMAGE, Design, adapter_path, junit_path, service_path, skeleton
from nexti_pack_spring_boot.equivalence import run_equivalence
from nexti_sandbox import DockerSandbox
from nexti_verification import differences

PACK = Path(__file__).parent / "fixtures" / "pago_orden"
LEGACY = Path(__file__).resolve().parents[4] / "adapters/source/sybase/tests/fixtures/pago_orden"
SAME = Design.model_validate_json((PACK / "design.same.json").read_text(encoding="utf-8"))
PAY = SAME.use_cases[0]
SUITE = Suite.model_validate_json((LEGACY / "characterization.json").read_text(encoding="utf-8"))
SOURCE = [SourceFile("sp/sp_pago_orden.sp", (LEGACY / "sp_pago_orden.sp").read_text(encoding="utf-8"))]
MASTER: GoldenMaster = asyncio.run(RecordedRunner(LEGACY / "golden", "replay").run(SOURCE, SUITE))


def reference_project(design: Design) -> dict[str, str]:
    """The reference target on the legacy's tables: the skeleton (with the generated adapter of sp_debito and the
    unit of work), the hand-written service and test, and the hand-written T-SQL adapters."""
    files = skeleton(design)
    path, content = wiring(design)
    files[path] = content
    files[service_path(design, PAY)] = (PACK / "PayOrderService.java").read_text(encoding="utf-8")
    files[junit_path(design, PAY)] = (PACK / "PayOrderServiceTest.java").read_text(encoding="utf-8")
    for port in design.ports:
        reference = PACK / "sybase" / f"Jdbc{port.name}.java"
        if reference.exists():
            files[adapter_path(design, port)] = reference.read_text(encoding="utf-8")
    return files


def _image(name: str) -> bool:
    try:
        found = subprocess.run(["docker", "image", "inspect", name], capture_output=True, check=False, timeout=30)  # noqa: S603, S607
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False
    return found.returncode == 0


@pytest.mark.skipif(os.environ.get("NEXTI_LIVE_ASE") != "1", reason="live Sybase ASE run: set NEXTI_LIVE_ASE=1")
def test_the_reference_target_reproduces_the_golden_master_on_the_legacys_engine() -> None:
    if not (_image(IMAGE) and _image("datagrip/sybase:16.0")):
        pytest.skip(f"the images {IMAGE} and datagrip/sybase:16.0 are needed")
    files = reference_project(SAME)
    debit = next(p for p in SAME.ports if p.legacy_program)
    assert "Generated by the platform (ADR-0055, same database)" in files[adapter_path(SAME, debit)]

    async def play() -> None:
        async with SameEngine(SOURCE, SUITE) as engine:
            run = await run_equivalence(DockerSandbox(image=IMAGE), files, SAME, PAY, MASTER, engine=engine)
        assert run.problem is None, run.problem
        assert (run.build.passed, run.build.failed) == (7, 0)
        # Judged as the verdict judges (returns, outputs, tables, surviving calls): the legacy's `undone` list is
        # diagnostic, and against the engine the rolled-back calls simply never reach the log.
        different = {c.name: (c.failure, differences(c.expected, c.actual)) for c in run.cases
                     if c.failure or differences(c.expected, c.actual)}  # fmt: skip
        assert len(run.cases) == 12
        assert different == {}
        # The calls the comparison judged came from the engine's log: the rolled-back debits are not among them.
        undone = next(c for c in run.cases if c.name == "failed_commission_undoes_the_payment")
        assert [call.program for call in undone.actual.calls] == []  # sp_cerror is infrastructure (masked)
        paid = next(c for c in run.cases if c.name == "separate_commission_is_a_second_debit")
        assert [call.arguments["@i_valor"] for call in paid.actual.calls] == ["100.0000", "1.5000"]

    asyncio.run(play())
