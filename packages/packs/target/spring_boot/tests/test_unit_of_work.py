"""The unit of work and the data strategy of the design reach the generated project (ADR-0055): the REST adapter
runs the use case inside one transaction, the savepoints of the legacy have a generated port adapter, and with
`same_database` the driver is the legacy's and the adapters of the called programs are generated by the platform
(named binding, return status, output parameters), never by a model."""

import json
from pathlib import Path

import pytest

from nexti_pack_spring_boot import Design, skeleton
from nexti_pack_spring_boot.generate import (
    adapter_path,
    controller_file,
    generated_adapters,
    pom_file,
    program_adapter_file,
    sybase_type,
    unit_of_work_adapter_file,
)

PACK = Path(__file__).parent / "fixtures" / "pago_orden"
DESIGN = Design.model_validate_json((PACK / "design.json").read_text(encoding="utf-8"))
PAY = DESIGN.use_cases[0]


def _with(**changes: object) -> Design:
    data = json.loads(DESIGN.model_dump_json(by_alias=True))
    data.update(changes)
    return Design.model_validate(data)


def test_the_rest_adapter_runs_the_use_case_inside_the_transaction_the_design_declares() -> None:
    _, controller = controller_file(DESIGN, PAY)
    assert "import org.springframework.transaction.support.TransactionTemplate;" in controller
    assert "return transaction.execute(status -> service.execute(request));" in controller
    assert "begin at 108, rollback at 119, rollback at 136, rollback at 155, commit at 161" in controller
    # Without a unit of work in the design nothing is wrapped: the controller is what it always was.
    plain = _with(use_cases=[{**json.loads(PAY.model_dump_json(by_alias=True)), "unit_of_work": None}])
    _, bare = controller_file(plain, plain.use_cases[0])
    assert "TransactionTemplate" not in bare
    assert "return service.execute(request);" in bare


def test_with_the_same_database_the_driver_is_the_legacys_and_the_called_programs_get_generated_adapters() -> None:
    _, pom = pom_file(DESIGN)
    assert "org.postgresql" in pom
    assert "jtds" not in pom
    same = _with(data_strategy="same_database")
    _, pom = pom_file(same)
    assert "net.sourceforge.jtds" in pom
    assert "org.postgresql" not in pom
    files = skeleton(same)
    debit = next(p for p in same.ports if p.legacy_program == "db_cuentas..sp_debito")
    path, adapter = program_adapter_file(same, debit)
    assert path == adapter_path(same, debit)
    assert files[path] == adapter
    assert "Generated by the platform (ADR-0055, same database)" in adapter
    assert "declare @nx_rc int, @o_secuencial int" in adapter
    assert ("exec @nx_rc = db_cuentas..sp_debito @i_cuenta = ?, @i_tipo = ?, @i_valor = ?, @i_referencia = ?, "
            "@o_secuencial = @o_secuencial output") in adapter  # fmt: skip
    assert "select @nx_rc as nx_rc, @o_secuencial as o_secuencial" in adapter
    assert 'throw new IllegalStateException("db_cuentas..sp_debito answered " + status);' in adapter
    assert "public long debit(String account, String type, java.math.BigDecimal amount, String reference)" in adapter
    assert "return value == null ? 0L : ((Number) value).longValue();" in adapter
    assert "jdbc.queryForMap(" in adapter
    assert ", account, type, amount, reference);" in adapter
    # With the data migrated nothing is generated for those ports: a developer writes them against the new tables.
    assert generated_adapters(DESIGN) == {}
    assert adapter_path(DESIGN, debit) not in skeleton(DESIGN)


def test_the_savepoints_of_the_legacy_are_a_generated_port_adapter() -> None:
    data = json.loads(DESIGN.model_dump_json(by_alias=True))
    data["ports"].append({"name": "UnitOfWork", "methods": [
        {"name": "savepoint", "inputs": [{"name": "name", "type": "text(var,30,iso8859-1)"}], "returns": None},
        {"name": "rollbackTo", "inputs": [{"name": "name", "type": "text(var,30,iso8859-1)"}], "returns": None},
    ]})  # fmt: skip
    data["use_cases"][0]["ports"].append("UnitOfWork")
    data["use_cases"][0]["unit_of_work"]["savepoints"] = [{"name": "beforeCommission", "legacy_line": 125}]
    data["use_cases"][0]["unit_of_work"]["rollbacks"][1] = {"legacy_line": 136, "outcome": "savepoint:beforeCommission"}
    design = Design.model_validate(data)
    port = next(p for p in design.ports if p.name == "UnitOfWork")
    path, adapter = unit_of_work_adapter_file(design, port)
    assert path == "src/main/java/com/bancoficticio/payments/adapters/out/jdbc/JdbcUnitOfWork.java"
    assert "connection().setSavepoint(name)" in adapter
    assert "connection().rollback(mark)" in adapter
    assert "DataSourceUtils.getConnection" in adapter
    assert skeleton(design)[path] == adapter
    # A rollback that names a savepoint the use case does not declare is refused by the design itself.
    data["use_cases"][0]["unit_of_work"]["rollbacks"][1]["outcome"] = "savepoint:nowhere"
    with pytest.raises(ValueError, match="unknown savepoint savepoint:nowhere"):
        Design.model_validate(data)


def test_the_t_sql_types_of_the_outputs_keep_the_legacy_precision() -> None:
    assert sybase_type("decimal(19,4,signed)") == "numeric(19,4)"
    assert sybase_type("integer(32,signed)") == "int"
    assert sybase_type("integer(64,signed)") == "bigint"
    assert sybase_type("text(fixed,3,iso8859-1)") == "char(3)"
    assert sybase_type("text(var,40,iso8859-1)") == "varchar(40)"
    assert sybase_type("timestamp(local)") == "datetime"
    assert sybase_type("boolean") == "bit"
