package nexti.jdbc;

import java.lang.reflect.InvocationHandler;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.lang.reflect.Proxy;
import java.math.BigDecimal;
import java.sql.CallableStatement;
import java.sql.Connection;

import java.sql.Driver;
import java.sql.DriverManager;
import java.sql.DriverPropertyInfo;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLFeatureNotSupportedException;
import java.sql.Statement;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.time.OffsetDateTime;
import java.util.Properties;
import java.util.logging.Logger;

/**
 * Generated by the platform (ADR-0055, same database): the legacy's Sybase ASE through jTDS, with what jTDS lacks of
 * JDBC 4.1 and 4.2. jTDS 1.3.1 is the open driver for Sybase but predates them: {@code rs.getObject(col, Type.class)},
 * {@code getSchema()}, {@code isValid()} or {@code closeOnCompletion()} throw AbstractMethodError, and a
 * {@code java.time} value cannot be bound. A service on the legacy's engine failed 32 of its 110 golden cases on that
 * alone (2026-10-20). URLs {@code jdbc:nexti:jtds:...} open jTDS and get these methods; everything else is jTDS's.
 */
public final class LegacyDriver implements Driver {

    public static final String PREFIX = "jdbc:nexti:";

    static {
        try {
            DriverManager.registerDriver(new LegacyDriver());
        } catch (SQLException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    private static Driver jtds() throws SQLException {
        try {
            return (Driver) Class.forName("net.sourceforge.jtds.jdbc.Driver").getDeclaredConstructor().newInstance();
        } catch (ReflectiveOperationException e) {
            throw new SQLException("jTDS is not on the class path", e);
        }
    }

    @Override
    public Connection connect(String url, Properties info) throws SQLException {
        if (!acceptsURL(url)) {
            return null;
        }
        Connection connection = jtds().connect("jdbc:" + url.substring(PREFIX.length()), info);
        return connection == null ? null : wrap(Connection.class, connection);
    }

    @Override
    public boolean acceptsURL(String url) {
        return url != null && url.startsWith(PREFIX);
    }

    @Override
    public DriverPropertyInfo[] getPropertyInfo(String url, Properties info) throws SQLException {
        return jtds().getPropertyInfo("jdbc:" + url.substring(PREFIX.length()), info);
    }

    @Override
    public int getMajorVersion() {
        return 1;
    }

    @Override
    public int getMinorVersion() {
        return 3;
    }

    @Override
    public boolean jdbcCompliant() {
        return false;
    }

    @Override
    public Logger getParentLogger() throws SQLFeatureNotSupportedException {
        throw new SQLFeatureNotSupportedException("no parent logger");
    }

    @SuppressWarnings("unchecked")
    static <T> T wrap(Class<T> type, T target) {
        Class<?>[] types = target instanceof CallableStatement ? new Class<?>[] {CallableStatement.class}
                : target instanceof PreparedStatement ? new Class<?>[] {PreparedStatement.class}
                : new Class<?>[] {type};
        return (T) Proxy.newProxyInstance(LegacyDriver.class.getClassLoader(), types, new Handler(target));
    }

    private static final class Handler implements InvocationHandler {
        private final Object target;

        Handler(Object target) {
            this.target = target;
        }

        @Override
        public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            String name = method.getName();
            int count = args == null ? 0 : args.length;
            if (target instanceof ResultSet rs && name.equals("getObject") && count == 2 && args[1] instanceof Class<?> c) {
                int column = args[0] instanceof Integer i ? i : rs.findColumn((String) args[0]);
                return typed(rs, column, c);
            }
            if (target instanceof PreparedStatement ps && name.equals("setObject") && count >= 2) {
                Object value = bindable(args[1]);
                if (value != args[1] || count == 3 && args[2] != null && !(args[2] instanceof Integer)) {
                    ps.setObject((Integer) args[0], value);
                    return null;
                }
            }
            if (target instanceof Connection c) {
                switch (name) {
                    case "getSchema": return null;
                    case "setSchema", "abort", "setNetworkTimeout": return null;
                    case "getNetworkTimeout": return 0;
                    case "isValid":
                        try (Statement s = c.createStatement()) {
                            s.execute("select 1");
                            return true;
                        } catch (SQLException e) {
                            return false;
                        }
                    default: break;
                }
            }
            if (target instanceof Statement && name.equals("closeOnCompletion")) {
                return null;
            }
            if (target instanceof Statement && name.equals("isCloseOnCompletion")) {
                return false;
            }
            if (name.equals("unwrap") && count == 1 && args[0] instanceof Class<?> c && c.isInstance(target)) {
                return target;
            }
            if (name.equals("isWrapperFor") && count == 1 && args[0] instanceof Class<?> c && c.isInstance(target)) {
                return true;
            }
            Object result;
            try {
                result = method.invoke(target, args);
            } catch (InvocationTargetException e) {
                throw e.getCause();
            }
            if (result instanceof ResultSet r && !(result instanceof Proxy)) {
                return wrap(ResultSet.class, r);
            }
            if (result instanceof Statement s && !(result instanceof Proxy)) {
                return wrap(Statement.class, s);
            }
            return result;
        }
    }

    /** A java.time value as the java.sql type jTDS binds; any other value as it is. */
    static Object bindable(Object value) {
        if (value instanceof LocalDateTime t) {
            return java.sql.Timestamp.valueOf(t);
        }
        if (value instanceof LocalDate d) {
            return java.sql.Date.valueOf(d);
        }
        if (value instanceof LocalTime t) {
            return java.sql.Time.valueOf(t);
        }
        if (value instanceof OffsetDateTime o) {
            return java.sql.Timestamp.from(o.toInstant());
        }
        return value;
    }

    /** The column as the type asked for, from what jTDS can read (null stays null). */
    @SuppressWarnings("unchecked")
    static <T> T typed(ResultSet rs, int column, Class<T> type) throws SQLException {
        Object value;
        if (type == LocalDateTime.class) {
            java.sql.Timestamp t = rs.getTimestamp(column);
            value = t == null ? null : t.toLocalDateTime();
        } else if (type == LocalDate.class) {
            java.sql.Date d = rs.getDate(column);
            value = d == null ? null : d.toLocalDate();
        } else if (type == LocalTime.class) {
            java.sql.Time t = rs.getTime(column);
            value = t == null ? null : t.toLocalTime();
        } else if (type == OffsetDateTime.class) {
            java.sql.Timestamp t = rs.getTimestamp(column);
            value = t == null ? null : t.toInstant().atOffset(java.time.ZoneOffset.UTC);
        } else if (type == BigDecimal.class) {
            value = rs.getBigDecimal(column);
        } else if (type == Integer.class) {
            int v = rs.getInt(column);
            value = rs.wasNull() ? null : v;
        } else if (type == Long.class) {
            long v = rs.getLong(column);
            value = rs.wasNull() ? null : v;
        } else if (type == Short.class) {
            short v = rs.getShort(column);
            value = rs.wasNull() ? null : v;
        } else if (type == Double.class) {
            double v = rs.getDouble(column);
            value = rs.wasNull() ? null : v;
        } else if (type == Boolean.class) {
            boolean v = rs.getBoolean(column);
            value = rs.wasNull() ? null : v;
        } else if (type == String.class) {
            value = rs.getString(column);
        } else if (type == byte[].class) {
            value = rs.getBytes(column);
        } else {
            value = rs.getObject(column);
        }
        if (value != null && !type.isInstance(value)) {
            throw new SQLException("column " + column + " is " + value.getClass().getName() + ", not " + type.getName());
        }
        return (T) value;
    }
}
