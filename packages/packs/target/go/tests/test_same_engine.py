"""`same_database` in the Go pack (ADR-0055, ADR-0056 phase H): the project talks to the legacy's Sybase ASE through the
tds driver of database/sql, the unit of work is the legacy's own T-SQL on one connection bound to the request, and the
port that replaces sp_debito gets an adapter the platform writes. The live test runs the reference service against the
platform's Sybase on a private network (opt-in: NEXTI_LIVE_ASE=1; needs datagrip/sybase:16.0 and the Go sandbox
image)."""

