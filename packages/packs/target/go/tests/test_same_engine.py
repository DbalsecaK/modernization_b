HERE = Path(__file__).parent / "fixtures" / "pago_orden"
PACKS = Path(__file__).resolve().parents[2]
LEGACY = PACKS.parents[1] / "adapters/source/sybase/tests/fixtures/pago_orden"
SAME = Design.model_validate_json((PACKS / "spring_boot/tests/fixtures/pago_orden/design.same.json").read_text("utf-8"))
PAY = SAME.use_cases[0]
SUITE = Suite.model_validate_json((LEGACY / "characterization.json").read_text(encoding="utf-8"))
SOURCE = [SourceFile("sp/sp_pago_orden.sp", (LEGACY / "sp_pago_orden.sp").read_text(encoding="utf-8"))]
DEBIT = "internal/adapters/pg/debit_gateway.go"


def test_with_the_same_database_the_project_uses_the_tds_driver_and_its_unit_of_work_as_t_sql() -> None:
    files = PACK.skeleton(SAME)
    assert "db/schema.sql" not in files  # the tables are the customer's: nothing creates them
    db = files["internal/adapters/pg/db.go"]
    assert '_ "github.com/thda/tds"' in db
    assert 'conn.ExecContext(ctx, "begin tran")' in db
    assert '"if @@trancount > 0 commit tran"' in db
    assert "func WithMessages(ctx context.Context)" in db
    assert "SetErrorhandler" in files["internal/adapters/pg/legacy.go"]
    debit = files[DEBIT]
    assert "generated by the platform, ADR-0055 same database" in debit
    assert '"@i_cuenta = "+literal(account)' in debit
    assert 'fmt.Errorf("db_cuentas..sp_debito answered %d", nxRC)' in debit
    assert PACK.adapter_path(SAME, next(p for p in SAME.ports if p.legacy_program)) == DEBIT
    assert "placeholders are `?`" in PACK.adapter_request(SAME, "OrderRepository", files)


def test_against_the_legacys_engine_the_plan_opens_it_and_no_port_is_faked() -> None:
    engine = EngineTarget(
        name="nexti-ase-x", network="nexti-eq-x", jdbc_url="jdbc:jtds:sybase://nexti-ase-x:5000/nexti_gm;prepareSQL=0",
        user="sa", password="x",  # noqa: S106 - the throw-away engine's own
        setup_for=lambda case: ["select 1"], calls_query="select program, args from nexti_gm..nx_call order by seq",
        programs={}, parse_args=lambda text: [],
    )  # fmt: skip
    assert engine_url(engine) == "tds://sa:x@nexti-ase-x:5000/nexti_gm?charset=iso_1"
    harness = plan(SAME, PAY, engine)
    assert harness["reset"] == []
    assert harness["calls"] == engine.calls_query
    assert "::text" not in harness["dump"][0]["sql"]  # the engine answers its own types
    source = glue(SAME, PAY, engine=True)
    assert "fakeDebitGateway" not in source
    assert "pg.NewDebitGateway(db)" in source
    assert "return pg.WithMessages(ctx)" in source


def _image(name: str) -> bool:
    try:
        found = subprocess.run(["docker", "image", "inspect", name], capture_output=True, check=False, timeout=30)  # noqa: S603, S607
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False
    return found.returncode == 0


def reference_project(design: Design) -> dict[str, str]:
    files = PACK.skeleton(design)
    files[PACK.service_path(design, PAY)] = (HERE / "pay_order_service.go").read_text(encoding="utf-8")
    files[PACK.test_path(design, PAY)] = (HERE / "pay_order_service_test.go").read_text(encoding="utf-8")
    for name in ("account_repository", "order_repository", "tariff_repository"):
        files[f"internal/adapters/pg/{name}.go"] = (HERE / "sybase" / f"{name}.go").read_text(encoding="utf-8")
    return files


@pytest.mark.skipif(os.environ.get("NEXTI_LIVE_ASE") != "1", reason="live Sybase ASE run: set NEXTI_LIVE_ASE=1")
def test_the_reference_target_reproduces_the_golden_master_on_the_legacys_engine() -> None:
    if not (_image(IMAGE) and _image("datagrip/sybase:16.0")):
        pytest.skip(f"the images {IMAGE} and datagrip/sybase:16.0 are needed")
    master: GoldenMaster = asyncio.run(RecordedRunner(LEGACY / "golden", "replay").run(SOURCE, SUITE))
    files = reference_project(SAME)

    async def play() -> None:
        async with SameEngine(SOURCE, SUITE) as engine:
            run = await run_equivalence(DockerSandbox(image=IMAGE), files, SAME, PAY, master, engine=engine)
        assert run.problem is None, run.problem
        assert (run.build.passed, run.build.failed) == (7, 0)
        different = {c.name: (c.failure, differences(c.expected, c.actual)) for c in run.cases
                     if c.failure or differences(c.expected, c.actual)}  # fmt: skip
        assert len(run.cases) == 12
        assert different == {}
        paid = next(c for c in run.cases if c.name == "separate_commission_is_a_second_debit")
        assert [call.arguments["@i_valor"] for call in paid.actual.calls] == ["100.0000", "1.5000"]
        assert "serializable" in run.raw.get("__concurrency__", {})

    asyncio.run(play())


def test_the_same_database_reference_project_compiles_and_its_tests_pass() -> None:
    if not _image(IMAGE):
        pytest.skip(f"the image {IMAGE} is needed")
    build = asyncio.run(PACK.compile_and_test(DockerSandbox(image=IMAGE), reference_project(SAME)))
    assert build.compiled, build.compile_errors
    assert (build.passed, build.failed) == (7, 0)


def test_the_delivery_carries_the_golden_master_as_a_command_without_the_platforms_credentials() -> None:
    import json

    from nexti_core.spec.equivalence import EquivalenceRun

    master: GoldenMaster = asyncio.run(RecordedRunner(LEGACY / "golden", "replay").run(SOURCE, SUITE))
    run = EquivalenceRun(build=None, cases=[], masks=[], raw={"a": {"name": "a", "tables": {}}})
    files = PACK.delivery_files(SAME, PAY, run, master)
    assert set(files) == {"cmd/nexti-equivalence/runtime.go", "cmd/nexti-equivalence/glue.go",
                          "testdata/golden-master/plan.json", "testdata/golden-master/cases.json",
                          "testdata/golden-master/expected.json", "testdata/golden-master/README.md"}  # fmt: skip
    assert json.loads(files["testdata/golden-master/plan.json"])["url"] == ""
    assert json.loads(files["testdata/golden-master/expected.json"]) == {"a": {"tables": {}}}
    assert "NEXTI_LEGACY_URL" in files["cmd/nexti-equivalence/runtime.go"]
    assert PACK.delivery_files(SAME, PAY, EquivalenceRun(None, [], [], "no harness"), master) == {}
