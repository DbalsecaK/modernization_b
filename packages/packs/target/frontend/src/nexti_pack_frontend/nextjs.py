"""The Next.js pack (spec 8.4, ADR-0028): the third flavour of the frontend pack, on the App Router. A deterministic
skeleton (the root layout, the home page with the navigation, one route folder per screen, the typed client, the
NexTI design system and the harness entry, from `templates/nextjs/`) and one client component per screen written by
the agent, the same contract and the same harness as React.

A screen is `src/app/screens/<module>/screen.tsx`: it starts with `'use client'` and exports by default a component
that receives `{ api, navigate }` (`ScreenProps` from `../types`). The route next to it (`page.tsx`, generated) gives
it the typed client and a `navigate(screenId)` over the Next.js router. Screens use no Next.js API, so the harness
mounts them in jsdom without the router, exactly like React pages.

With `bff=True` the skeleton adds `src/app/api/[...path]/route.ts`, a BFF that only forwards `/api/**` to the
backend (`NEXTI_BACKEND_URL`); the client calls the same origin either way."""

import json
from collections.abc import Sequence
from typing import Any

from nexti_pack_frontend.contract import ScreenContract
from nexti_pack_frontend.skeleton import project_name, render, templates

NAME = "nextjs"
VERSIONS = {
    "next": "16.3.8", "react": "19.3.0", "react-dom": "19.3.0", "typescript": "6.0.3", "esbuild": "0.28.2",
    "@types/node": "24.19.1", "@types/react": "19.3.0", "@types/react-dom": "19.3.0",
}  # fmt: skip
TSCONFIG = {
    "compilerOptions": {
        "target": "ES2022",
        "module": "ESNext",
        "moduleResolution": "bundler",
        "jsx": "react-jsx",
        "strict": True,
        "noEmit": True,
        "skipLibCheck": True,
        "resolveJsonModule": True,
        "isolatedModules": True,
        "lib": ["ES2022", "DOM", "DOM.Iterable"],
        "rootDir": ".",
        "types": [],
        "plugins": [{"name": "next"}],
        "paths": {"@/*": ["./src/*"], "@nexti/ds": ["./ds/index.ts"], "@nexti/ds/*": ["./ds/*"]},
    },
    "include": ["next-env.d.ts", "src"],
}
ROUTE = """'use client'
// The route of {id}: its screen with the typed client and the app's navigation (generated by the platform).
import Screen from './screen'
import {{ useScreenProps }} from '../use-screen-props'

export default function Page() {{
  return <Screen {{...useScreenProps()}} />
}}
"""


def route_of(contract: ScreenContract) -> str:
    return f"/screens/{contract.module}"


def screen_path(contract: ScreenContract) -> str:
    return f"src/app/screens/{contract.module}/screen.tsx"


def _routes(screens: Sequence[ScreenContract], title: str) -> str:
    routes = "\n".join(f"  {json.dumps(s.id)}: {json.dumps(route_of(s))}," for s in screens)
    links = "\n".join(f"  {{ href: {json.dumps(route_of(s))}, name: {json.dumps(s.name or s.id)} }}," for s in screens)
    start = json.dumps(screens[0].id if screens else "")
    return (
        "// The routes of the screens (generated by the platform): one App Router folder per screen.\n"
        f"export const TITLE = {json.dumps(title)}\n\n"
        f"export const START = {start}\n\n"
        f"export const ROUTES: Record<string, string> = {{\n{routes}\n}}\n\n"
        "export const LINKS: { href: string; name: string }[] = [\n" + links + "\n]\n"
    )


def skeleton(
    contract: dict[str, Any], screens: Sequence[ScreenContract], title: str, *, bff: bool = False
) -> dict[str, str]:
    """Every file but the screens. `contract` is the OpenAPI document of the backend; `bff` adds the BFF route."""
    manifest = {
        "name": project_name(title), "private": True, "version": "0.1.0",
        "scripts": {"dev": "next dev", "build": "next build", "start": "next start"},
        "dependencies": {k: VERSIONS[k] for k in ("next", "react", "react-dom")},
        "devDependencies": {k: VERSIONS[k] for k in ("typescript", "@types/node", "@types/react", "@types/react-dom")},
    }  # fmt: skip
    files = render(NAME, contract, screens, title, lambda s: f"import {s.component} from './{s.module}/screen'",
                   {"package.json": manifest, "tsconfig.json": TSCONFIG})  # fmt: skip
    files["src/app/screens/routes.ts"] = _routes(screens, title)
    for screen in screens:
        files[f"src/app/screens/{screen.module}/page.tsx"] = ROUTE.format(id=screen.id)
    if bff:
        files.update(templates("nextjs-bff"))
    return files
