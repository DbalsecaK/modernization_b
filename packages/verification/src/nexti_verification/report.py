    target_not_run: Sequence[str] = ()  # "file lines a-b"
    ambiguous_parameters: Sequence[str] = ()  # "program.@param" the calls pass as NULL where a default exists
    unreachable: Mapping[str, str] = field(default_factory=dict)
    data_strategy: str | None = None
    engine: str = ""


