def _t(key: str, language: Language, **values: Any) -> str:
    return _T[key][language].format(**values)


def programmer_report(language: Language, verdict: Verdict, certainty: Certainty | None, items: ReportItems) -> str:
    """The report as Markdown, in the language asked for."""
    lines = [f"# {_t('title', language)}", "", _t("intro", language, module=verdict.module), ""]
    lines += [f"## {_t('verdict', language)}", "", f"**{verdict.verdict}**", ""]
    if certainty is not None:
        frontier = certainty.frontier_es if language == "es" else certainty.frontier_en
        lines += [f"## {_t('certainty', language)}", "", f"**{certainty.percent} %** — {frontier}", "",
                  f"### {_t('components', language)}", ""]  # fmt: skip
        for c in certainty.components:
            detail = c.detail_es if language == "es" else c.detail_en
            lines.append(f"- {detail} ({c.score:.0f}/{c.weight})")
        lines.append("")
    lines += _section("masks", language, list(items.masks))
    substitutes: list[str] = []
    for program, answers in items.substitutes.items():
        substitutes.append(f"**{program}**")
        for a in answers:
            outputs = ", ".join(f"{k} = {v}" for k, v in a.outputs.items()) or "—"
            messages = "; ".join(a.messages) or "—"
            substitutes.append(f"  - {_t('case', language)} `{a.case}`: {_t('returns', language)} {a.returns}, "
                               f"{_t('outputs', language)} {outputs}, "
                               f"{_t('messages', language)} {messages}")  # fmt: skip
    lines += _section("substitutes", language, substitutes, raw=True)
    lines += _section("quirks", language, list(items.quirks_without_case))
    lines += _section("uncited", language, list(items.uncited_statements))
    lines += _section("not_run", language, list(items.target_not_run))
    lines += _section("ambiguous", language, list(items.ambiguous_parameters))
    lines += _section("unreachable", language, [f"`{k}`: {v}" for k, v in items.unreachable.items()])
    shadow = [_t("golden_it", language)]
    if items.data_strategy == "same_database":
        shadow.append(_t("datasource", language))
    if items.substitutes:
        shadow.append(_t("real_programs", language))
    shadow.append(_t("contract", language))
    primary = [_t("concurrency", language), _t("shadow_period", language)]
    if items.masks:
        primary.append(_t("masks_review", language))
    lines += [f"## {_t('before_shadow', language)}", ""] + [f"{n}. {s}" for n, s in enumerate(shadow, 1)] + [""]
    lines += [f"## {_t('before_primary', language)}", ""] + [f"{n}. {s}" for n, s in enumerate(primary, 1)] + [""]
    return "\n".join(lines)


def _section(key: str, language: Language, entries: Sequence[str], raw: bool = False) -> list[str]:
    out = [f"## {_t(key, language)}", "", _t(f"{key}_hint", language), ""]
    if not entries:
        out += [_t("nothing", language), ""]
        return out
    out += [e if (raw and e.startswith("  ")) else (e if raw else f"- {e}") for e in entries]
    out.append("")
    return out
